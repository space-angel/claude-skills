class WikiError(Exception):
    """코드 + 설명 + "다음에 할 일" 한 문장. details는 항목별 하위 코드 목록."""

    def __init__(self, code: str, message: str, next_action: str, details: Optional[list] = None,
                 exit_code: int = 1):
        super().__init__(message)
        self.code, self.message, self.next_action = code, message, next_action
        self.details = details or []
        self.exit_code = exit_code

    def as_dict(self) -> dict:
        return {"ok": False, "error": {"code": self.code, "message": self.message,
                                       "next": self.next_action, "details": self.details}}


def finding(code: str, message: str, **extra) -> dict:
    item = {"code": code, "message": message}
    item.update(extra)
    return item


