def render_area_file(preamble: str, records: List[dict]) -> str:
    body = "\n\n".join(render_block(r) for r in sorted(records, key=lambda r: r["id"]))
    return preamble.rstrip() + "\n\n" + body + "\n"


def area_summary(preamble: str) -> str:
    m = re.search(r"영역 요약[:：]?\s*(?:\*\*)?\s*[:：]?\s*(.+)", preamble or "")
    return m.group(1).strip().strip("*").strip() if m else ""


def state_equal(a: dict, b: dict, fields=STATE_FIELDS) -> bool:
    for key in fields:
        x, y = a.get(key), b.get(key)
        if key == "value":
            x, y = normalize(x), normalize(y)
        elif key == "scope":
            x, y = x or empty_scope(), y or empty_scope()
        elif key == "replaced_by":
            x, y = sorted(x or []), sorted(y or [])
        elif key in ("interpretation", "review_by", "evidence", "reason", "title"):
            x, y = x or None, y or None
        if x != y:
            return False
    return True


def field_same(a: dict, b: dict, key: str) -> bool:
    """HAND_EDIT 판정용 정확 비교 (값도 글자 그대로)."""
    x, y = a.get(key), b.get(key)
    if key == "scope":
        return (x or empty_scope()) == (y or empty_scope())
    if key == "replaced_by":
        return sorted(x or []) == sorted(y or [])
    if key == "locked":
        return bool(x) == bool(y)
    if isinstance(x, str) or isinstance(y, str):
        return (x or "").strip() == (y or "").strip()
    return x == y


def effective_value(rec: dict) -> str:
    if rec.get("status") == "deprecated":
        return "폐기:" + ",".join(sorted(rec.get("replaced_by") or []))
    return normalize(rec.get("value"))


