def source_label(rec: dict) -> str:
    src = rec.get("source") or ""
    if src == "import" and rec.get("origin_source"):
        src = rec["origin_source"]
    return SOURCE_LABELS.get(src, src)


def changelog_values(prev: Optional[dict], rec: dict) -> str:
    if prev is None:
        return f"(없음) → {rec.get('value') or ''}"
    if rec.get("status") == "deprecated" and prev.get("status") != "deprecated":
        return f"{prev.get('value') or ''} → 폐기(대체: {', '.join(rec.get('replaced_by') or [])})"
    if prev.get("value") != rec.get("value"):
        return f"{prev.get('value') or ''} → {rec.get('value') or ''}"
    checks = (("scope", "적용 범위", render_scope), ("title", "제목", None),
              ("always_on", "항상 적용", lambda v: "예" if v else "아니오"),
              ("interpretation", "해석", None), ("review_by", "다시 볼 날", None),
              ("locked", "잠금", lambda v: "예" if v else "아니오"), ("status", "상태", lambda v: "사용" if v == "active" else "폐기"))
    for key, label, fmt in checks:
        if not state_equal(prev, rec, (key,)):
            f = fmt or (lambda v: v or "(없음)")
            return f"{label}: {f(prev.get(key)) or '(없음)'} → {f(rec.get(key)) or '(없음)'}"
    return f"{prev.get('value') or ''} → {rec.get('value') or ''}"


def changelog_line(wiki: Wiki, rec: dict, prev: Optional[dict]) -> str:
    when = wiki.at(rec["at"]).strftime("%Y-%m-%d %H:%M")
    ver = f"{'new' if prev is None else prev['version']}→{rec['version']}"
    reason = clean_cell(rec.get("origin_reason") or rec.get("reason"))
    if rec.get("change_kind") == "wording":
        reason = "[문구] " + reason
    if rec.get("is_revert") and "되돌림" not in reason:
        reason += f" (v{rec.get('reverted_to')}로 되돌림)"
    cells = [when, clean_cell(rec.get("by")), f"{rec['id']} {ver}", clean_cell(changelog_values(prev, rec)),
             reason, clean_cell(source_label(rec))]
    return " | ".join(cells)


def render_changelog(wiki: Wiki) -> str:
    lines = [GENERATED_MARK, "# CHANGELOG", "",
             "> history.jsonl에서 다시 만들어요. 결정은 `wiki.py change`로 바꾸세요.",
             "> 형식: 날짜 시각 | 누가 | ID 이전버전→새버전 | 이전 값 → 새 값 | 이유 | 출처", ""]
    prev_by_id: Dict[str, dict] = {}
    for rec in wiki.history():
        lines.append(changelog_line(wiki, rec, prev_by_id.get(rec["id"])))
        prev_by_id[rec["id"]] = rec
    return "\n".join(lines) + "\n"


def all_areas(wiki: Wiki, latest: Dict[str, dict]) -> List[str]:
    cfg_areas = list(wiki.cfg.get("areas", []))
    extra = sorted({d.split(".")[0] for d in latest} - set(cfg_areas))
    return cfg_areas + extra


def render_index(wiki: Wiki) -> str:
    latest = wiki.latest()
    active = [r for r in latest.values() if r.get("status") == "active"]
    always = sorted([r for r in active if r.get("always_on")], key=lambda r: r["id"])
    limit = wiki.cfg.get("always_on_limit", 10)
    out = [GENERATED_MARK, "# 결정 사항 목차", "",
           "> 작업 전에 이 파일을 먼저 읽고, 이번 작업과 관련된 영역 파일만 여세요.",
           "> 결정은 파일을 직접 고치지 말고 `wiki.py change`로 바꿔요. 바뀐 기록: CHANGELOG.md", "",
           f"## 항상 적용되는 결정 ({len(always)}개, 최대 {limit}개)", ""]
    if always:
        out += ["| ID | 제목 | 파일 |", "|---|---|---|"]
        out += [f"| {r['id']} | {clean_cell(r['title'])} | decisions/{r['id'].split('.')[0]}.md |" for r in always]
    else:
        out.append("(없음)")
    out += ["", "## 영역", "", "| 영역 | 파일 | 한 줄 요약 | 사용 | 폐기 |", "|---|---|---|---|---|"]
    areas = all_areas(wiki, latest)
    for a in areas:
        recs = [r for r in latest.values() if r["id"].split(".")[0] == a]
        pre, _b, _o = wiki.read_area(a)
        n_act = sum(1 for r in recs if r.get("status") == "active")
        out.append(f"| {a} | decisions/{a}.md | {clean_cell(area_summary(pre))} | {n_act} | {len(recs) - n_act} |")
    out += ["", "## 영역별 결정"]
    for a in areas:
        recs = sorted([r for r in latest.values() if r["id"].split(".")[0] == a], key=lambda r: r["id"])
        if not recs:
            continue
        out += ["", f"### {a}", ""]
        for r in recs:
            if r.get("status") == "active":
                out.append(f"- `{r['id']}` v{r['version']} — {r['title']}")
            else:
                out.append(f"- ~~`{r['id']}`~~ v{r['version']} — {r['title']} (폐기 → {', '.join(r.get('replaced_by') or [])})")
    return "\n".join(out) + "\n"


def decision_lines(r: dict) -> List[str]:
    lines = [f"- `{r['id']}` (v{r['version']}) {r['value']}"]
    if r.get("interpretation"):
        lines.append(f"  - 해석: {r['interpretation']}")
    return lines


def render_managed_block(wiki: Wiki) -> str:
    latest = wiki.latest()
    limit = int(wiki.cfg.get("always_on_limit", 10))
    always = sorted([r for r in latest.values() if r.get("status") == "active" and r.get("always_on")],
                    key=lambda r: r["id"])[:limit]
    body = [BLOCK_START, GENERATED_MARK, "## 팀 결정 사항 (항상 적용)", ""]
    for r in always:
        body += decision_lines(r)
    if not always:
        body.append("(항상 적용되는 결정이 아직 없어요)")
    body += ["", "다른 결정은 `.wiki/INDEX.md`를 먼저 읽고 이번 작업과 관련된 영역 파일만 여세요. "
                 "결정과 다르게 만들게 되면 만들기 전에 사람에게 먼저 물어요.", BLOCK_END]
    return "\n".join(body)


def merge_block(existing: Optional[str], block: str) -> str:
    if existing is None:
        return block + "\n"
    s, e = existing.find(BLOCK_START), existing.find(BLOCK_END)
    if s != -1 and e != -1 and e > s:
        return existing[:s] + block + existing[e + len(BLOCK_END):]
    sep = "" if existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
    return existing + sep + block + "\n"


def generated_outputs(wiki: Wiki) -> Dict[Path, Optional[str]]:
    """다시 만들 파일 → 내용 (None이면 지울 생성물)."""
    out: Dict[Path, Optional[str]] = {wiki.root / "INDEX.md": render_index(wiki),
                                      wiki.root / "CHANGELOG.md": render_changelog(wiki)}
    exports = wiki.cfg.get("exports", [])
    latest = wiki.latest()
    active = sorted([r for r in latest.values() if r.get("status") == "active"], key=lambda r: r["id"])
    block = render_managed_block(wiki)
    for target, fname in (("claude", "CLAUDE.md"), ("agents", "AGENTS.md")):
        if target in exports:
            p = wiki.project / fname
            out[p] = merge_block(read_text(p), block)
    by_area: Dict[str, List[dict]] = {}
    for r in active:
        if (r.get("scope") or {}).get("code"):
            by_area.setdefault(r["id"].split(".")[0], []).append(r)
    for target, sub, ext in (("claude-rules", ".claude/rules", ".md"), ("cursor", ".cursor/rules", ".mdc")):
        d = wiki.project / sub
        wanted = {}
        if target in exports:
            for area, recs in sorted(by_area.items()):
                globs = sorted({g for r in recs for g in r["scope"]["code"]})
                if ext == ".md":
                    head = ["---", "paths:"] + [f'  - "{g}"' for g in globs] + ["---"]
                else:
                    head = ["---", f"description: bandit-wiki {area} 결정 사항", f"globs: {','.join(globs)}",
                            "alwaysApply: false", "---"]
                body = [GENERATED_MARK, f"# {area} 결정 사항 (bandit-wiki)", "",
                        "이 경로의 파일을 고칠 때 지키는 팀 결정이에요. 다르게 만들게 되면 먼저 사람에게 물어요.", ""]
                for r in recs:
                    body += decision_lines(r)
                wanted[d / f"bandit-{area}{ext}"] = "\n".join(head + body) + "\n"
            if ext == ".mdc":
                always = [r for r in active if r.get("always_on")][: int(wiki.cfg.get("always_on_limit", 10))]
                body = ["---", "description: bandit-wiki 항상 적용 결정", "alwaysApply: true", "---", GENERATED_MARK,
                        "# 팀 결정 사항 (항상 적용)", ""]
                for r in always:
                    body += decision_lines(r)
                wanted[d / "bandit-always.mdc"] = "\n".join(body) + "\n"
        out.update(wanted)
        if d.exists():  # 더 이상 필요 없는 우리 생성물만 지운다
            for p in sorted(d.glob(f"bandit-*{ext}")):
                if p not in wanted and GENERATED_MARK in (read_text(p) or ""):
                    out[p] = None
    return out


def drift(wiki: Wiki) -> List[Tuple[Path, Optional[str]]]:
    changed = []
    for path, content in sorted(generated_outputs(wiki).items(), key=lambda kv: str(kv[0])):
        current = read_text(path)
        if content is None:
            if current is not None:
                changed.append((path, None))
        elif current != content:
            changed.append((path, content))
    return changed


def apply_sync(wiki: Wiki) -> List[str]:
    written = []
    for path, content in drift(wiki):
        if content is None:
            path.unlink()
            written.append(f"지움 {wiki.rel(path)}")
        else:
            atomic_write(path, content)
            written.append(f"씀 {wiki.rel(path)}")
    return written


