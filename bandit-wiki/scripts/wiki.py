def compute_pending(wiki: Wiki, as_of: Optional[dt.datetime] = None,
                    extra: Optional[List[dict]] = None) -> Tuple[List[dict], List[dict]]:
    """(확인 필요 목록, 건너뛴 목록). extra = 아직 저장 안 한 새 버전(미리보기용)."""
    hist = [r for r in wiki.history() if as_of is None or wiki.at(r["at"]) <= as_of] + list(extra or [])
    by_id: Dict[str, List[dict]] = {}
    for r in hist:
        by_id.setdefault(r["id"], []).append(r)
    issues, active, _ = wiki.link_state(as_of)
    acked: Dict[tuple, int] = {}
    for a in wiki.acks(as_of):
        key = (a["issue"], a["id"])
        acked[key] = max(acked.get(key, 0), int(a["version"]))
    items, skipped = [], []
    for (issue, did) in sorted(active):
        link = active[(issue, did)]
        snap = issues.get(issue, {})
        base = {"issue": issue, "id": did}
        if snap.get("status") == "canceled":
            skipped.append(dict(base, reason="skip_canceled"))
            continue
        assignee = wiki.canon(snap.get("assignee"))
        if not assignee:
            skipped.append(dict(base, reason="no_assignee"))
            continue
        vers = by_id.get(did)
        if not vers:
            skipped.append(dict(base, reason="not_found"))
            continue
        seen = max(int(link.get("linked_version") or 0), acked.get((issue, did), 0))
        later = [v for v in vers if v["version"] > seen]
        relevant = [v for v in later if v.get("change_kind") != "wording" and wiki.canon(v.get("by")) != assignee]
        if not relevant:
            skipped.append(dict(base, reason="up_to_date" if not later else "wording_or_self"))
            continue
        latest = vers[-1]
        seen_rec = ([v for v in vers if v["version"] <= seen] or [None])[-1]
        if seen_rec is not None and effective_value(seen_rec) == effective_value(latest):
            skipped.append(dict(base, reason="closed_by_revert"))
            continue
        to_value = latest["value"] if latest.get("status") == "active" else \
            f"폐기(대체: {', '.join(latest.get('replaced_by') or [])})"
        items.append({
            "issue": issue, "issue_title": snap.get("title"), "issue_status": snap.get("status"),
            "id": did, "title": latest.get("title"), "assignee": assignee,
            "from_version": seen, "to_version": latest["version"],
            "from_value": seen_rec["value"] if seen_rec else None, "to_value": to_value,
            "reason": latest.get("reason"), "by": latest.get("by"), "at": latest.get("at"),
            "source": latest.get("source"), "interpretation": latest.get("interpretation"),
            "change_kinds": [v.get("change_kind") for v in later],
        })
    items.sort(key=lambda x: (x["at"] or "", x["assignee"], x["issue"], x["id"]))
    return items, skipped


