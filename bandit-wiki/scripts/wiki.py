def cmd_sync(args) -> int:
    wiki = Wiki(args.wiki_root)
    changed = drift(wiki)
    edits = wiki.hand_edits()
    if args.check:
        rel = [wiki.rel(p) for p, _ in changed]
        if args.json:
            emit_json({"ok": not rel and not edits, "drift": rel, "hand_edits": [e["id"] for e in edits]})
        else:
            for r in rel:
                say(f"  다름: {r}")
            for e in edits:
                say(f"  HAND_EDIT: {e['id']} ({', '.join(e['fields'])})")
            say("생성물이 원본과 같아요." if not rel and not edits else
                "GENERATED_DRIFT: 생성물이나 결정 파일이 기록과 달라요. 다음에 할 일: python3 wiki.py sync (HAND_EDIT는 adopt) 후 커밋하세요.")
        return 1 if (rel or edits) else 0
    written = apply_sync(wiki)
    if written:
        wiki.log("sync", f"{len(written)}개 파일 다시 만듦")
    if args.json:
        emit_json({"ok": True, "written": written, "hand_edits": [e["id"] for e in edits]})
        return 0
    say("다시 만든 파일: " + ", ".join(w.split(" ", 1)[1] for w in written) if written else "바뀐 생성물이 없어요.")
    for e in edits:
        say(f"  HAND_EDIT: {e['id']} — python3 wiki.py adopt {e['id']} --kind rule|wording --apply")
    return 0


def cmd_lint(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = wiki.latest()
    active = {k: v for k, v in latest.items() if v.get("status") == "active"}
    errors, warnings, infos = [], [], []
    today = wiki.now().date().isoformat()
    # 깨진 scope 경로
    total = broken = 0
    for did in sorted(active):
        for g in active[did]["scope"].get("code") or []:
            total += 1
            if count_glob(wiki, g) == 0:
                broken += 1
                sug = suggest_paths(wiki, g)
                warnings.append(finding("SCOPE_PATH_MISSING", f"{did}: '{g}'에 맞는 파일이 없어요." + (f" 후보: {', '.join(sug)}" if sug else ""), id=did))
    if total:
        (warnings if broken else infos).insert(0, finding("SCOPE_SUMMARY", f"적용 범위 코드 경로 {total}개 중 {broken}개가 없는 곳을 가리켜요.",
                                                          total=total, broken=broken))
    for did in sorted(active):
        rb = active[did].get("review_by")
        if rb and rb < today:
            warnings.append(finding("REVIEW_OVERDUE", f"{did}: 다시 볼 날({rb})이 지났어요.", id=did))
    _issues, links, _ = wiki.link_state()
    linked_ids = {d for (_i, d) in links}
    orphans = sorted(set(active) - linked_ids)
    if orphans:
        infos.append(finding("ORPHAN", f"연결된 이슈가 없는 결정 {len(active)}개 중 {len(orphans)}개: {', '.join(orphans[:10])}" +
                             (" …" if len(orphans) > 10 else ""), ids=orphans))
    changed = drift(wiki)
    for p, _c in changed:
        warnings.append(finding("GENERATED_DRIFT", f"{wiki.rel(p)}가 다시 만든 결과와 달라요.", path=wiki.rel(p)))
    for e in wiki.hand_edits():
        errors.append(finding("HAND_EDIT", f"{e['id']}: 결정 파일이 기록과 달라요 ({', '.join(e['fields'])}).", id=e["id"]))
    for did, r in sorted(latest.items()):
        if r.get("status") == "deprecated":
            for x in r.get("replaced_by") or []:
                if x not in latest:
                    errors.append(finding("REPLACED_BY_BROKEN", f"{did}: 대체 ID '{x}'가 없어요.", id=did))
                elif latest[x].get("status") == "deprecated":
                    warnings.append(finding("REPLACED_BY_DEPRECATED", f"{did}: 대체 결정 '{x}'도 폐기됐어요.", id=did))
    limit = int(wiki.cfg.get("always_on_limit", 10))
    n_always = sum(1 for r in active.values() if r.get("always_on"))
    (errors if n_always > limit else infos).append(finding("ALWAYS_ON_COUNT", f"항상 적용 결정 {n_always}개 (최대 {limit}개)."))
    ids = sorted(active)
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            s = max(jaccard(active[a]["title"], active[b]["title"]), jaccard(active[a]["value"], active[b]["value"]))
            if s >= DUPLICATE_THRESHOLD:
                warnings.append(finding("DUPLICATE_SUSPECT", f"{a} ↔ {b} 가 비슷해요 (유사도 {s:.2f}).", ids=[a, b]))
    for e in history_integrity(wiki):
        errors.append(e)
    issues, _l, _ = wiki.link_state()
    prog = sorted(i for i, s in issues.items() if s.get("status") == "in_progress")
    if prog:
        unlinked = [i for i in prog if not any(li == i for (li, _d) in links)]
        infos.append(finding("LINK_COVERAGE", f"진행 중 이슈 {len(prog)}건 중 {len(unlinked)}건이 결정과 연결되지 않았어요.",
                             total=len(prog), unlinked=len(unlinked)))
    fixed = []
    if args.fix and changed:
        fixed = apply_sync(wiki)
        warnings = [w for w in warnings if w["code"] != "GENERATED_DRIFT"]
    wiki.log("lint", f"에러 {len(errors)}, 경고 {len(warnings)}, 정보 {len(infos)}")
    if args.json:
        emit_json({"ok": not errors, "errors": errors, "warnings": warnings, "info": infos, "fixed": fixed})
        return 1 if errors else 0
    say(f"위키 점검: 에러 {len(errors)}건, 경고 {len(warnings)}건, 정보 {len(infos)}건")
    for label, group in (("에러", errors), ("경고", warnings), ("정보", infos)):
        for x in group:
            say(f"  [{label}] {x['code']}: {x['message']}")
    if fixed:
        say("고친 것(생성물 재생성): " + ", ".join(w.split(" ", 1)[1] for w in fixed))
    elif any(w["code"] == "GENERATED_DRIFT" for w in warnings):
        say("생성물 드리프트는 python3 wiki.py lint --fix 로 고칠 수 있어요. 나머지는 사람에게 하나씩 물어보세요.")
    return 1 if errors else 0


def cmd_impact(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = get_latest_or_fail(wiki, args.id)
    by = wiki.identity(args.by, required=False)
    issues, active, _ = wiki.link_state()
    links = []
    for (i, d) in sorted(active):
        if d != args.id:
            continue
        snap = issues.get(i, {})
        assignee = wiki.canon(snap.get("assignee"))
        if snap.get("status") == "canceled":
            note = "취소된 이슈라 건너뜀"
        elif not assignee:
            note = "담당자가 없어 건너뜀"
        elif by and assignee == by:
            note = "바꾸는 본인이라 건너뜀"
        else:
            note = "확인 요청 대상"
        links.append({"issue": i, "title": snap.get("title"), "assignee": assignee, "status": snap.get("status"), "note": note})
    targets = [x for x in links if x["note"] == "확인 요청 대상"]
    files = sum(count_glob(wiki, g) for g in latest["scope"].get("code") or [])
    result = {"id": args.id, "version": latest["version"], "always_on": latest["always_on"], "links": links,
              "checks": len(targets), "assignees": sorted({x["assignee"] for x in targets}), "scope_files": files}
    warnings = []
    if args.value is not None:
        trial = dict(latest, value=args.value, interpretation=None)
        _e, warnings = validate(wiki, trial, wiki.latest())
        olds = [v for v in wiki.versions(args.id)[:-1] if normalize(v["value"]) == normalize(args.value)]
        result["revert_to"] = olds[-1]["version"] if olds else None
        result["no_change"] = normalize(args.value) == normalize(latest["value"])
    result["warnings"] = warnings
    if args.json:
        emit_json(result)
        return 0
    say(f"{args.id} (v{latest['version']}){' — 항상 적용' if latest['always_on'] else ''}")
    say(f"  연결된 이슈 {len(links)}건, 확인 요청이 갈 이슈 {len(targets)}건 (담당자 {len(result['assignees'])}명: {', '.join(result['assignees']) or '없음'})")
    for x in links:
        say(f"  - {x['issue']} {x['title'] or ''} [{ISSUE_STATUS_LABELS.get(x['status'], x['status'])}] {x['assignee'] or '담당자 없음'} — {x['note']}")
    say(f"  적용 범위에 걸리는 파일 {files}개")
    say("  문구만 바꾸면(--kind wording) 확인 요청을 만들지 않아요.")
    if result.get("revert_to"):
        say(f"  이 값은 v{result['revert_to']}과 같아요 — 되돌림으로 저장돼요.")
    print_warnings(warnings)
    return 0


def read_hook_path() -> Optional[str]:
    try:
        data = json.loads(sys.stdin.read() or "{}")
    except (ValueError, OSError):
        return None
    ti = data.get("tool_input") or {}
    return ti.get("file_path") or ti.get("notebook_path") or ti.get("path")


def cmd_for_path(args) -> int:
    path = args.path
    if path in (None, "-"):
        path = read_hook_path()
    if not path:
        return 0
    wiki = Wiki(args.wiki_root)
    p = Path(path)
    if p.is_absolute():
        try:
            rel = Path(os.path.realpath(p)).relative_to(os.path.realpath(wiki.project)).as_posix()
        except ValueError:
            return 0
    else:
        rel = strip_dot(p.as_posix())
    hits = []
    for did, r in sorted(wiki.latest().items()):
        if r.get("status") != "active":
            continue
        globs = [g for g in r["scope"].get("code") or [] if glob_matches(g, rel)]
        if globs:
            hits.append({"id": did, "version": r["version"], "title": r["title"], "value": r["value"],
                         "interpretation": r.get("interpretation"), "globs": globs})
    if args.json:
        emit_json({"path": rel, "decisions": hits})
        return 0
    if not hits:
        return 0
    lines = [f"[bandit-wiki] {rel} 에 걸린 팀 결정 {len(hits)}개:"]
    for h in hits:
        lines.append(f"- {h['id']} (v{h['version']}): {h['value']}")
        lines.append(f"  해석: {h['interpretation']}" if h["interpretation"] else "  해석: (없음 — 숫자·비교어가 있으면 어떻게 읽었는지 한 줄로 말하세요)")
