def new_record(base: dict, **kw) -> dict:
    """§3 필드 순서로 레코드를 만든다."""
    r = dict(base)
    r.update(kw)
    keys = ("id", "version", "title", "value", "reason", "scope", "always_on", "status", "replaced_by",
            "locked", "review_by", "interpretation", "change_kind", "is_revert", "reverted_to", "evidence",
            "source", "by", "actor", "at")
    out = {k: r.get(k) for k in keys}
    out["scope"] = out["scope"] or empty_scope()
    out["replaced_by"] = sorted(out["replaced_by"] or [])
    out["always_on"] = bool(out["always_on"])
    out["locked"] = bool(out["locked"])
    out["is_revert"] = bool(out["is_revert"])
    for k in ("origin_source", "origin_reason", "import_kind"):
        if kw.get(k):
            out[k] = kw[k]
    return out


def detect_revert(wiki: Wiki, rec: dict, prev: Optional[dict]) -> None:
    if prev is None or rec.get("status") != "active":
        return
    if normalize(rec["value"]) == normalize(prev["value"]):
        return
    for old in reversed(wiki.versions(rec["id"])[:-1]):
        if normalize(old["value"]) == normalize(rec["value"]):
            rec["is_revert"], rec["reverted_to"], rec["change_kind"] = True, old["version"], "revert"
            return


def stale_interpretation(rec: dict, prev: Optional[dict]) -> List[dict]:
    """값이 바뀌었는데 해석이 이전 버전 글자 그대로 따라온 경우 (예: 24시간 → 12시간인데 해석은 '24시간은…')."""
    if prev is None or rec.get("status") != "active" or not rec.get("interpretation"):
        return []
    if normalize(rec.get("value")) == normalize(prev.get("value")):
        return []
    if (rec.get("interpretation") or "").strip() != (prev.get("interpretation") or "").strip():
        return []
    return [finding("INTERPRETATION_STALE", f"값이 바뀌었는데 해석은 v{prev['version']} 그대로예요: \"{rec['interpretation']}\". 새 값에도 맞나요?",
                    next="맞지 않으면 change는 --interpretation \"…\"(지우려면 \"\"), 직접 고친 파일은 해석 줄을 고치세요.")]


def check_area_clean(wiki: Wiki, area: str) -> None:
    edits = [e for e in wiki.hand_edits() if e["id"].split(".")[0] == area]
    if edits:
        ids = ", ".join(e["id"] for e in edits)
        raise WikiError("HAND_EDIT", f"decisions/{area}.md가 기록(history)과 달라요: {ids}",
                        f"python3 wiki.py adopt {edits[0]['id']} --kind rule|wording --apply 로 먼저 받아들이거나, 파일을 git으로 되돌리세요.")


def impact_of(wiki: Wiki, rec: dict) -> dict:
    items, _ = compute_pending(wiki, extra=[rec])
    hits = [i for i in items if i["id"] == rec["id"] and i["to_version"] == rec["version"]]
    _issues, active, _ = wiki.link_state()
    linked = sorted(i for (i, d) in active if d == rec["id"])
    return {"linked_issues": linked, "checks": [{"issue": h["issue"], "assignee": h["assignee"]} for h in hits],
            "assignees": sorted({h["assignee"] for h in hits})}


def print_warnings(warnings: List[dict]) -> None:
    if not warnings:
        return
    say("확인할 점 (저장은 되지만 사람에게 물어보세요):")
    for w in warnings:
        say(f"  - {w['code']}: {w['message']}" + (f" {w['next']}" if w.get("next") else ""))


def finish_write(wiki: Wiki, args, op: str, recs: List[Tuple[dict, Optional[dict]]], warnings: List[dict],
                 skip_clean: bool = False) -> int:
    """recs = [(새 레코드, 직전 레코드)]. 미리보기 또는 저장."""
    if not skip_clean:
        for rec, _prev in recs:
            check_area_clean(wiki, rec["id"].split(".")[0])
    previews = []
    for rec, prev in recs:
        previews.append({"record": rec, "previous_version": prev["version"] if prev else None,
                         "changelog_line": changelog_line(wiki, rec, prev), "impact": impact_of(wiki, rec)})
    if not args.apply:
        if args.json:
            emit_json({"ok": True, "applied": False, "op": op, "changes": previews, "warnings": warnings})
            return 0
        for p in previews:
            rec = p["record"]
            say(f"[미리보기] {rec['id']} v{p['previous_version'] or 0} → v{rec['version']} ({KIND_LABELS.get(rec['change_kind'], rec['change_kind'])})")
            if p["previous_version"]:
                prev = [x for _r, x in recs if x and x["id"] == rec["id"]][0]
                say(f"  이전 값: {prev['value']}")
            say(f"  새 값: {rec['value']}" + ("  [폐기]" if rec["status"] == "deprecated" else ""))
            say(f"  이유: {rec['reason']}")
            if rec.get("is_revert"):
                say(f"  되돌림: v{rec['reverted_to']} 값과 같아요")
            imp = p["impact"]
            if rec["change_kind"] == "wording":
                say(f"  영향: 문구만 바꿈 — 연결된 이슈 {len(imp['linked_issues'])}건에 확인 요청을 만들지 않아요")
            else:
                who = ", ".join(imp["assignees"]) or "없음"
                say(f"  영향: 연결된 이슈 {len(imp['linked_issues'])}건, 확인 요청 {len(imp['checks'])}건 (담당자: {who})")
            say(f"  CHANGELOG: {p['changelog_line']}")
        print_warnings(warnings)
        say("저장하려면 같은 명령에 --apply를 붙이세요.")
        return 0
    for rec, _prev in recs:
        wiki.add_history(rec)
    for area in sorted({rec["id"].split(".")[0] for rec, _ in recs}):
        wiki.render_area(area)
    for rec, prev in recs:
        wiki.log(op, f"{rec['id']} v{prev['version'] if prev else 0}→v{rec['version']} {rec['change_kind']} ({rec['by']})")
    written = apply_sync(wiki)
    if args.json:
        emit_json({"ok": True, "applied": True, "op": op, "changes": previews, "warnings": warnings, "synced": written})
        return 0
    for p in previews:
        say(f"저장했어요: {p['record']['id']} v{p['record']['version']}")
        say(f"  CHANGELOG: {p['changelog_line']}")
        n = len(p["impact"]["checks"])
        if n:
            say(f"  확인 요청 {n}건이 생겼어요 (담당자: {', '.join(p['impact']['assignees'])}). python3 wiki.py pending 으로 보세요.")
    print_warnings(warnings)
    if written:
        say("다시 만든 파일: " + ", ".join(w.split(" ", 1)[1] for w in written))
    return 0


def scope_from_args(args, base: Optional[dict] = None) -> dict:
    scope = {k: list(v) for k, v in (base or empty_scope()).items()}
    for kind in ("code", "api", "screen", "doc"):
        val = getattr(args, f"scope_{kind}", None)
        if val is not None:
            scope[kind] = split_list(val)
    return scope


def yes_no(val: Optional[str], name: str) -> Optional[bool]:
    if val is None:
        return None
    v = val.strip().lower()
    if v in ("yes", "y", "true", "예", "1"):
        return True
    if v in ("no", "n", "false", "아니오", "0"):
        return False
    raise WikiError("USAGE", f"{name} 값 '{val}'을 알 수 없어요.", f"{name} yes 또는 {name} no 로 적으세요.", exit_code=2)


