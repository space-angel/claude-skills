def check_issue_key(issue: str) -> None:
    if not ISSUE_RE.match(issue):
        raise WikiError("VALIDATION_FAILED", f"이슈 키 '{issue}'를 쓸 수 없어요.", "BK-12 처럼 영문·숫자·하이픈으로 적으세요.", exit_code=2)


def issue_event(wiki: Wiki, issue: str, snap: Optional[dict], args, by: str, now: str) -> Optional[dict]:
    ev = {"type": "issue", "issue": issue}
    if args.status and args.status not in ISSUE_STATUSES:
        raise WikiError("USAGE", f"상태 '{args.status}'를 알 수 없어요.", f"--status {'|'.join(ISSUE_STATUSES)} 중 하나로 적으세요.", exit_code=2)
    for k, v in (("title", args.title), ("assignee", wiki.canon(args.assignee) if args.assignee else args.assignee),
                 ("status", args.status)):
        if v is not None and (snap is None or snap.get(k) != v):
            ev[k] = v
    if snap is None and "status" not in ev:
        ev["status"] = "todo"
    if len(ev) == 2:
        return None
    ev.update({"by": by, "at": now})
    return ev


def write_events(wiki: Wiki, args, events: List[dict], path: Path, op: str, summary: str, preview_lines: List[str]) -> int:
    if not args.apply:
        if args.json:
            emit_json({"ok": True, "applied": False, "events": events})
        else:
            say("[미리보기]")
            for l in preview_lines:
                say("  " + l)
            say("저장하려면 같은 명령에 --apply를 붙이세요." if events else "기록할 것이 없어요.")
        return 0
    for e in events:
        append_jsonl(path, e)
    if events:
        wiki.log(op, summary)
    if args.json:
        emit_json({"ok": True, "applied": True, "events": events})
    else:
        say(f"기록했어요 ({len(events)}건)." if events else "기록할 것이 없어요.")
        for l in preview_lines:
            say("  " + l)
    return 0


def cmd_link(args) -> int:
    wiki = Wiki(args.wiki_root)
    check_issue_key(args.issue)
    by, now = wiki.identity(args.by), iso(wiki.now())
    issues, active, _ = wiki.link_state()
    snap = issues.get(args.issue)
    if snap is None and not args.title:
        raise WikiError("VALIDATION_FAILED", f"처음 연결하는 이슈 '{args.issue}'예요.", "--title 로 이슈 제목을 적으세요 (--assignee, --status 도).",
                        details=[finding("MISSING_FIELD", "빠진 칸: 이슈 제목", fields=["이슈 제목"])])
    events, lines = [], []
    ev = issue_event(wiki, args.issue, snap, args, by, now)
    if ev:
        events.append(ev)
        lines.append(f"이슈 {args.issue}: " + ", ".join(f"{k}={ev[k]}" for k in ("title", "assignee", "status") if k in ev))
    latest = wiki.latest()
    for did in args.ids:
        rec = latest.get(did)
        if rec is None:
            raise WikiError("NOT_FOUND", f"'{did}' 결정이 없어요.", "INDEX.md에서 ID를 확인하세요.")
        if rec.get("status") == "deprecated":
            raise WikiError("DEPRECATED", f"'{did}'는 폐기된 결정이에요.", f"대체 결정({', '.join(rec.get('replaced_by') or [])})에 연결하세요.")
        if (args.issue, did) in active:
            lines.append(f"{args.issue} ↔ {did}: 이미 연결돼 있어요 (v{active[(args.issue, did)]['linked_version']}부터 봄)")
            continue
        events.append({"type": "link", "issue": args.issue, "id": did, "linked_version": rec["version"], "by": by, "at": now})
        lines.append(f"{args.issue} ↔ {did} 연결 (v{rec['version']}부터 봄)")
    others = sorted(d for (i, d) in active if i == args.issue and d not in args.ids)
    if others:
        lines.append(f"기존 연결은 그대로 둬요: {', '.join(others)}")
    return write_events(wiki, args, events, wiki.links_path, "link", f"{args.issue} ↔ {', '.join(args.ids)}", lines)


