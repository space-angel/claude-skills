def cmd_metrics(args) -> int:
    wiki = Wiki(args.wiki_root)
    now = wiki.now()
    start = now - dt.timedelta(days=args.days)
    hist = [r for r in wiki.history() if start <= wiki.at(r["at"]) <= now]
    changes = [r for r in hist if r.get("change_kind") != "import"]
    people: Dict[str, int] = {}
    sources: Dict[str, int] = {}
    kinds: Dict[str, int] = {}
    for r in changes:
        people[r["by"]] = people.get(r["by"], 0) + 1
        sources[r["source"]] = sources.get(r["source"], 0) + 1
        kinds[r["change_kind"]] = kinds.get(r["change_kind"], 0) + 1
    # 확인 필요 생성 수: 각 버전이 저장된 직후 계산으로 그 버전에 대한 확인 필요가 생긴 (이슈, 결정, 버전)
    created = set()
    for r in hist:
        items, _ = compute_pending(wiki, as_of=wiki.at(r["at"]))
        for it in items:
            if it["id"] == r["id"] and it["to_version"] == r["version"]:
                created.add((it["issue"], it["id"], it["to_version"]))
    acks = [a for a in wiki.acks() if start <= wiki.at(a["at"]) <= now]
    affected = [a for a in acks if a.get("affected")]
    unknown = [a for a in affected if a.get("known") is False]
    waits = [(wiki.at(a["at"]) - wiki.at(a["changed_at"])).total_seconds() / 3600 for a in acks if a.get("changed_at")]
    issues, links, _ = wiki.link_state()
    prog = sorted(i for i, s in issues.items() if s.get("status") == "in_progress")
    prog_linked = [i for i in prog if any(li == i for (li, _d) in links)]
    res = {
        "days": args.days, "from": iso(start), "to": iso(now),
        "changes": len(changes), "imported": len(hist) - len(changes),
        "people": dict(sorted(people.items(), key=lambda kv: (-kv[1], kv[0]))),
        "sources": dict(sorted(sources.items())), "kinds": dict(sorted(kinds.items())),
        "coverage": {"in_progress": len(prog), "linked": len(prog_linked)},
        "funnel": {"created": len(created), "answered": len(acks), "affected": len(affected), "unknown": len(unknown)},
        "median_hours_to_answer": round(statistics.median(waits), 2) if waits else None,
    }
    if args.json:
        emit_json(res)
        return 0
    say(f"지난 {args.days}일 ({start.strftime('%Y-%m-%d')} ~ {now.strftime('%Y-%m-%d')})")
    say(f"- 결정 변경 {len(changes)}건" + (f" (가져오기 {res['imported']}건 제외)" if res["imported"] else ""))
    say(f"- 바꾼 사람 {len(people)}명: " + (", ".join(f"{k} {v}건" for k, v in res["people"].items()) or "없음"))
    say("- 출처: " + (", ".join(f"{SOURCE_LABELS.get(k, k)} {pct(v, len(changes))}" for k, v in res["sources"].items()) or "없음"))
    say("- 종류: " + (", ".join(f"{KIND_LABELS.get(k, k)} {pct(v, len(changes))}" for k, v in res["kinds"].items()) or "없음"))
    say(f"- 연결 커버리지: 진행 중 이슈 {len(prog)}건 중 결정과 연결된 이슈 {len(prog_linked)}건")
    f = res["funnel"]
    say(f"- 확인 퍼널: 확인 필요 {f['created']}건 → 답함 {pct(f['answered'], f['created'])} → 관계있다 {pct(f['affected'], f['answered'])} → 몰랐다 {pct(f['unknown'], f['affected'])}")
    say(f"- 바뀐 뒤 답까지 걸린 시간 중앙값: {res['median_hours_to_answer']}시간" if waits else "- 바뀐 뒤 답까지 걸린 시간: 답이 없어요")
    return 0


