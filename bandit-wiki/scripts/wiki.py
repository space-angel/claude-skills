def strip_dot(path: str) -> str:
    while path.startswith("./"):
        path = path[2:]
    return path


def glob_to_regex(glob: str) -> re.Pattern:
    i, out = 0, ""
    while i < len(glob):
        c = glob[i]
        if glob.startswith("**/", i):
            out += r"(?:.*/)?"
            i += 3
            continue
        if glob.startswith("**", i):
            out += ".*"
            i += 2
            continue
        if c == "*":
            out += "[^/]*"
        elif c == "?":
            out += "[^/]"
        elif c == "{":
            j = glob.find("}", i)
            if j > i:
                out += "(?:" + "|".join(re.escape(x) for x in glob[i + 1:j].split(",")) + ")"
                i = j + 1
                continue
            out += re.escape(c)
        else:
            out += re.escape(c)
        i += 1
    return re.compile("^" + out + "$")


def glob_matches(glob: str, path: str) -> bool:
    g = strip_dot(glob.strip())
    g = g.rstrip("/") if not any(ch in g for ch in "*?{") else g
    if not any(ch in g for ch in "*?{"):
        return path == g or path.startswith(g + "/")
    return bool(glob_to_regex(g).match(path))


def count_glob(wiki: Wiki, glob: str) -> int:
    files, _dirs = wiki.project_files()
    return sum(1 for f in files if glob_matches(glob, f))


def suggest_paths(wiki: Wiki, glob: str, limit: int = 3) -> List[str]:
    """깨진 경로의 후보: 같은 이름 폴더 → 가장 가까운 상위 폴더의 비슷한 이름."""
    files, dirs = wiki.project_files()
    segs = strip_dot(glob.strip()).split("/")
    static = []
    for s in segs:
        if any(ch in s for ch in "*?{"):
            break
        static.append(s)
    if not static:
        return []
    last = static[-1]
    tail = "/".join(segs[len(static):])
    cands = []
    for d in sorted(dirs | set(files)):
        base = d.rsplit("/", 1)[-1]
        if base == last and d != "/".join(static):
            cands.append((0.0 - difflib.SequenceMatcher(None, d, "/".join(static)).ratio(), d))
    found = [d for _s, d in sorted(cands)]
    # 가장 가까운 존재하는 상위 폴더에서 비슷한 이름
    for depth in range(len(static) - 1, -1, -1):
        parent = "/".join(static[:depth])
        if parent and parent not in dirs:
            continue
        target = static[depth]
        children = sorted({p.split("/")[depth] for p in (dirs | set(files))
                           if (p.startswith(parent + "/") if parent else True) and len(p.split("/")) > depth})
        scored = sorted((-difflib.SequenceMatcher(None, target, ch).ratio(), ch) for ch in children)
        for score, ch in scored:
            if -score >= 0.4:
                found.append("/".join(static[:depth] + [ch]))
        break
    out = []
    for p in found:
        full = p + ("/" + tail if tail else "")
        if full not in out and full != glob:
            out.append(full)
    return out[:limit]


