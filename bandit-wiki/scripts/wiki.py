def cmd_init(args) -> int:
    root = find_root(args)
    if (root / "config.json").exists():
        raise WikiError("ALREADY_INITIALIZED", f"{root} 에 위키가 이미 있어요.", "설정을 바꾸려면 .wiki/config.json을 직접 고치세요.")
    cfg = dict(DEFAULT_CONFIG)
    cfg["areas"] = [a for a in split_ids(args.areas) if a]
    cfg["timezone"] = args.timezone
    for a in cfg["areas"]:
        if not re.match(r"^[a-z]+$", a):
            raise WikiError("VALIDATION_FAILED", f"영역 이름 '{a}'은 영문 소문자만 쓸 수 있어요.", "--areas app,data 처럼 다시 적으세요.", exit_code=2)
    root.mkdir(parents=True, exist_ok=True)
    atomic_write(root / "config.json", json.dumps(cfg, ensure_ascii=False, indent=2) + "\n")
    for sub in ("sources", "decisions"):
        (root / sub).mkdir(exist_ok=True)
        (root / sub / ".gitkeep").touch()
    for name in ("history.jsonl", "links.jsonl", "acks.jsonl"):
        (root / name).touch()
    atomic_write(root / ".gitattributes", "*.jsonl merge=union\nlog.md merge=union\n")
    atomic_write(root / ".gitignore", ".local/\n")
    atomic_write(root / "log.md", "# 작업 기록\n\n> wiki.py가 한 줄씩 붙여요. 지우거나 고치지 않아요.\n\n")
    wiki = Wiki(root)
    wiki.log("init", f"영역 {', '.join(cfg['areas']) or '(없음)'}")
    written = apply_sync(wiki)
    if args.json:
        emit_json({"ok": True, "root": str(root), "config": cfg, "synced": written})
        return 0
    say(f"위키를 만들었어요: {root}")
    say(f"  영역: {', '.join(cfg['areas']) or '(없음) — .wiki/config.json의 areas에 추가하세요'}")
    say("  다시 만든 파일: " + ", ".join(w.split(" ", 1)[1] for w in written))
    say("다음: python3 wiki.py new --id 영역.주제.규칙 --title … --value … --reason …")
    return 0


def cmd_check(args) -> int:
    wiki = Wiki(args.wiki_root)
    files, latest = wiki.file_states(), wiki.latest()
    ids = args.ids or sorted(set(files) | set(latest))
    unknown = [i for i in ids if i not in files and i not in latest]
    if unknown:
        raise WikiError("NOT_FOUND", f"이런 결정이 없어요: {', '.join(unknown)}", "INDEX.md에서 ID를 확인하세요.")
    others = dict(latest)
    others.update({k: v for k, v in files.items()})
    report = []
    for did in ids:
        st = files.get(did)
        errs, warns = [], []
        if st is None:
            errs.append(finding("HAND_EDIT", "기록에는 있는데 결정 파일에 블록이 없어요 (지우면 안 돼요)."))
        else:
            errs += st["_problems"]
            e2, w2 = validate(wiki, st, others)
            errs += e2
            warns += w2
            if st["_unknown"]:
                warns.append(finding("UNKNOWN_FIELD", "모르는 칸: " + ", ".join(st["_unknown"])))
        report.append({"id": did, "errors": errs, "warnings": warns})
    for e in wiki.hand_edits():
        if e["id"] in ids and e["kind"] != "removed":
            r = [x for x in report if x["id"] == e["id"]][0]
            hv = e["latest"]["version"] if e["latest"] else 0
            r["errors"].append(finding("HAND_EDIT", f"파일이 기록 최신 버전(v{hv})과 달라요: {', '.join(e['fields'])}",
                                       next=f"python3 wiki.py adopt {e['id']} --kind rule|wording --apply"))
    hist_errs = history_integrity(wiki)
    n_err = sum(len(r["errors"]) for r in report) + len(hist_errs)
    n_warn = sum(len(r["warnings"]) for r in report)
    if args.json:
        emit_json({"ok": n_err == 0, "errors": n_err, "warnings": n_warn, "decisions": report, "history": hist_errs})
        return 1 if n_err else 0
    say(f"검사: 결정 {len(ids)}개, 에러 {n_err}건, 경고 {n_warn}건")
    for r in report:
        for e in r["errors"]:
            say(f"  [에러] {r['id']}: {e['code']} {e['message']}" + (f" → {e['next']}" if e.get("next") else ""))
        for w in r["warnings"]:
            say(f"  [경고] {r['id']}: {w['code']} {w['message']}")
    for e in hist_errs:
        say(f"  [에러] history: {e['code']} {e['message']}")
    if n_err:
        say("다음에 할 일: 에러를 먼저 고치세요. HAND_EDIT는 adopt로 받아들이면 돼요.")
    return 1 if n_err else 0


def history_integrity(wiki: Wiki) -> List[dict]:
    out, last = [], {}
    for r in wiki.history():
        expect = last.get(r["id"], 0) + 1
        first_import = r["id"] not in last and r.get("source") == "import" and r["version"] >= 1
        if r["version"] != expect and not first_import:
            out.append(finding("HISTORY_CONFLICT", f"{r['id']} v{r['version']}가 순서에 맞지 않아요 (기대: v{expect}). 두 브랜치에서 동시에 바꿨을 수 있어요."))
        last[r["id"]] = r["version"]
    return out


def common_fields(wiki: Wiki, args) -> dict:
    return {"source": args.source, "by": wiki.identity(args.by), "actor": args.actor, "at": iso(wiki.now())}


def cmd_new(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = wiki.latest()
    if args.id in latest:
        raise WikiError("VERSION_CONFLICT", f"'{args.id}'는 이미 있는 결정이에요 (v{latest[args.id]['version']}).",
                        f"바꾸려면 python3 wiki.py change {args.id} --base-version {latest[args.id]['version']} … 를 쓰세요.")
    lock = yes_no(args.lock, "--lock")
    if lock and args.actor == "ai":
        raise WikiError("STANDARD_LOCKED", "잠금은 사람만 걸 수 있어요.", "--lock 을 빼거나 사람이 --actor human 으로 저장하세요.")
    rec = new_record({}, id=args.id, version=1, title=args.title, value=args.value, reason=args.reason,
                     scope=scope_from_args(args), always_on=args.always_on, status="active", locked=lock,
                     review_by=args.review_by, interpretation=args.interpretation, change_kind="addition",
                     evidence=args.evidence, **common_fields(wiki, args))
    errors, warnings = validate(wiki, rec, latest)
    raise_if_errors(errors)
    return finish_write(wiki, args, "new", [(rec, None)], warnings)


def get_latest_or_fail(wiki: Wiki, did: str) -> dict:
    latest = wiki.latest().get(did)
    if latest is None:
        raise WikiError("NOT_FOUND", f"'{did}' 결정이 없어요.", "INDEX.md에서 ID를 확인하거나, 새 결정이면 new를 쓰세요.")
    return latest


def guard_change(wiki: Wiki, latest: dict, actor: str) -> None:
    if latest.get("status") == "deprecated":
        raise WikiError("DEPRECATED", f"'{latest['id']}'는 폐기된 결정이에요.",
                        f"대체 결정({', '.join(latest.get('replaced_by') or []) or '없음'})을 바꾸세요. 되살리려면 revert를 쓰세요.")
    if latest.get("locked") and actor == "ai":
        raise WikiError("STANDARD_LOCKED", f"'{latest['id']}'는 잠긴 결정이라 AI가 바꿀 수 없어요.",
                        "바꿀 필요가 있다고 사람에게 알리고, 사람이 --actor human 으로 바꾸게 하세요.")


def cmd_change(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = get_latest_or_fail(wiki, args.id)
    if latest.get("status") == "deprecated":
        guard_change(wiki, latest, args.actor)
    if args.base_version != latest["version"]:
        raise WikiError("VERSION_CONFLICT", f"기준 버전 v{args.base_version}이 최신 v{latest['version']}과 달라요. 그사이 누가 바꿨어요.",
                        f"최신 값({latest['value']})을 다시 보여 주고 사람 확인 후 --base-version {latest['version']} 으로 다시 저장하세요.")
    if not args.kind:
        raise WikiError("KIND_REQUIRED", "문구만 바꿨나요, 규칙을 바꿨나요?",
                        "--kind wording(문구만, 연결 이슈에 확인 요청 없음) 또는 --kind rule(규칙) 을 붙이세요.")
    guard_change(wiki, latest, args.actor)
    lock = yes_no(args.lock, "--lock")
    if lock is not None and args.actor == "ai":
        raise WikiError("STANDARD_LOCKED", "잠금은 사람만 바꿀 수 있어요.", "--lock 을 빼고 다시 실행하세요.")
    if not args.reason:
        raise WikiError("VALIDATION_FAILED", "저장할 수 없어요.", "--reason 으로 왜 바꾸는지 한 문장을 적으세요. 지어내지 말고 사람에게 물어보세요.",
                        details=[finding("MISSING_FIELD", "빠진 칸: 이유", fields=["이유"])])
    always = yes_no(args.always_on, "--always-on")
    over = {"title": args.title, "value": args.value, "evidence": args.evidence, "review_by": args.review_by,
            "interpretation": args.interpretation}
    base = {k: v for k, v in latest.items()}
    for k, v in over.items():
        if v is not None:
            base[k] = v or None
    rec = new_record(base, version=latest["version"] + 1, reason=args.reason, scope=scope_from_args(args, latest.get("scope")),
                     always_on=latest["always_on"] if always is None else always,
                     locked=latest.get("locked") if lock is None else lock, change_kind=args.kind,
                     is_revert=False, reverted_to=None, **common_fields(wiki, args))
    if state_equal(rec, latest):
        raise WikiError("NO_CHANGE", "바뀐 칸이 없어요 (값은 공백·마침표·전각 차이를 무시하고 비교해요).",
                        "새 버전을 만들지 않았어요. 바꿀 값을 다시 확인하세요.")
    detect_revert(wiki, rec, latest)
    errors, warnings = validate(wiki, rec, wiki.latest())
    raise_if_errors(errors)
    warnings += stale_interpretation(rec, latest)
    return finish_write(wiki, args, "change", [(rec, latest)], warnings)


def cmd_deprecate(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = get_latest_or_fail(wiki, args.id)
    guard_change(wiki, latest, args.actor)
    if not args.reason:
        raise WikiError("VALIDATION_FAILED", "저장할 수 없어요.", "--reason 으로 왜 폐기하는지 적으세요.",
                        details=[finding("MISSING_FIELD", "빠진 칸: 이유", fields=["이유"])])
    rec = new_record(latest, version=latest["version"] + 1, reason=args.reason, status="deprecated",
                     replaced_by=split_ids(args.replaced_by), change_kind="deprecate", is_revert=False,
                     reverted_to=None, always_on=False, **common_fields(wiki, args))
    errors, _w = validate(wiki, rec, wiki.latest())
    raise_if_errors(errors)
    return finish_write(wiki, args, "deprecate", [(rec, latest)], [])


def cmd_revert(args) -> int:
    wiki = Wiki(args.wiki_root)
    latest = get_latest_or_fail(wiki, args.id)
    if latest.get("locked") and args.actor == "ai":
        guard_change(wiki, latest, args.actor)
    target = [v for v in wiki.versions(args.id) if v["version"] == args.to_version]
    if not target:
        raise WikiError("NOT_FOUND", f"'{args.id}'에 v{args.to_version}이 없어요.", f"1부터 {latest['version']} 사이 버전을 고르세요.")
    target = target[0]
    if not args.reason:
        raise WikiError("VALIDATION_FAILED", "저장할 수 없어요.", "--reason 으로 왜 되돌리는지 적으세요 ('v1로 되돌림' 대신 까닭을).",
                        details=[finding("MISSING_FIELD", "빠진 칸: 이유", fields=["이유"])])
    rec = new_record(latest, version=latest["version"] + 1, title=target["title"], value=target["value"],
                     scope=target.get("scope"), always_on=target.get("always_on"), status=target.get("status"),
                     replaced_by=target.get("replaced_by"), interpretation=target.get("interpretation"),
                     review_by=target.get("review_by"), reason=args.reason, change_kind="revert",
                     is_revert=True, reverted_to=target["version"], evidence=args.evidence or latest.get("evidence"),
                     **common_fields(wiki, args))
    if state_equal(rec, latest):
        raise WikiError("NO_CHANGE", f"v{args.to_version}과 지금(v{latest['version']})이 같아요.", "되돌릴 게 없어요. 버전을 다시 확인하세요.")
    errors, warnings = validate(wiki, rec, wiki.latest())
    raise_if_errors(errors)
    return finish_write(wiki, args, "revert", [(rec, latest)], warnings)


def cmd_adopt(args) -> int:
    wiki = Wiki(args.wiki_root)
    all_edits = wiki.hand_edits()
    edits = all_edits
    if args.ids:
        missing = [i for i in args.ids if i not in {e["id"] for e in edits}]
        if missing:
            raise WikiError("NO_CHANGE", f"직접 고친 흔적이 없어요: {', '.join(missing)}", "python3 wiki.py check 로 HAND_EDIT 목록을 보세요.")
        edits = [e for e in edits if e["id"] in args.ids]
        areas = {e["id"].split(".")[0] for e in edits}
        rest = [e["id"] for e in all_edits if e["id"] not in args.ids and e["id"].split(".")[0] in areas]
        if rest:
            raise WikiError("HAND_EDIT", f"같은 영역 파일에 받아들이지 않은 직접 수정이 더 있어요: {', '.join(rest)}",
                            "그 ID도 함께 adopt 하거나, 그 부분을 git으로 되돌린 뒤 다시 실행하세요.")
    if not edits:
        say("받아들일 직접 수정이 없어요.") if not args.json else emit_json({"ok": True, "changes": []})
        return 0
    by = wiki.identity(args.by)
    now, latest_all = iso(wiki.now()), wiki.latest()
    others = dict(latest_all)
    recs, warnings, render_only = [], [], []
    for e in edits:
        f, h = e["file"], e["latest"]
        if e["kind"] == "removed":
            raise WikiError("HAND_EDIT", f"'{e['id']}' 블록이 파일에서 지워졌어요. 결정은 지우지 않아요.",
                            f"git으로 블록을 되살리고, 쓰지 않으려면 python3 wiki.py deprecate {e['id']} --replaced-by … 를 쓰세요.")
        if f["_problems"]:
            raise WikiError("VALIDATION_FAILED", f"'{e['id']}' 블록 형식이 틀렸어요.", "칸 형식을 고친 뒤 다시 실행하세요.", details=f["_problems"])
        if f["_file"] != e["id"].split(".")[0]:
            raise WikiError("VALIDATION_FAILED", f"'{e['id']}'가 decisions/{f['_file']}.md에 있어요.",
                            f"decisions/{e['id'].split('.')[0]}.md 로 옮긴 뒤 다시 실행하세요.")
        st = {k: v for k, v in f.items() if not k.startswith("_")}
        if h is None:
            rec = new_record(st, version=1, change_kind="addition", is_revert=False, reverted_to=None,
                             source=args.source, by=by, actor=args.actor, at=now)
            prev = None
        else:
            if e["fields"] == ["버전"]:
                render_only.append(e["id"].split(".")[0])
                continue
            guard_change(wiki, h, args.actor)
            if state_equal(st, h):
                kind = "wording"  # 이유·근거만 고친 경우: 상태는 같으니 확인 요청을 만들지 않는다
            elif st.get("status") == "deprecated" and h.get("status") == "active":
                kind = "deprecate"
            elif not args.kind:
                raise WikiError("KIND_REQUIRED", f"'{e['id']}': 문구만 바꿨나요, 규칙을 바꿨나요?",
                                "--kind wording 또는 --kind rule 을 붙이세요.")
            else:
                kind = args.kind
            if not st.get("reason"):
                raise WikiError("VALIDATION_FAILED", f"'{e['id']}' 이유 칸이 비었어요.", "결정 파일의 이유 칸에 왜 바꿨는지 한 문장을 적은 뒤 다시 실행하세요.",
                                details=[finding("MISSING_FIELD", "빠진 칸: 이유", fields=["이유"])])
            rec = new_record(st, version=h["version"] + 1, change_kind=kind, is_revert=False, reverted_to=None,
                             source=args.source, by=by, actor=args.actor, at=now)
            if (st.get("reason") or "") == (h.get("reason") or "") and not state_equal(st, h):
                warnings.append(finding("REASON_UNCHANGED", f"'{e['id']}' 이유 칸이 이전 버전과 같아요. 이번에 바꾼 까닭을 적었나요?"))
            detect_revert(wiki, rec, h)
            prev = h
        errs, warns = validate(wiki, rec, others)
        raise_if_errors(errs)
        warnings += warns + stale_interpretation(rec, prev)
        recs.append((rec, prev))
    if render_only and args.apply:
        for area in sorted(set(render_only)):
            wiki.render_area(area)
    if not recs:
        say("버전 번호만 달라서 파일을 기록대로 다시 썼어요." if args.apply else "버전 번호만 달라요. --apply 로 파일을 기록대로 다시 써요.")
        return 0
    # adopt는 파일이 이미 바뀌어 있으므로 HAND_EDIT 검사를 건너뛴다 (다른 직접 수정은 위에서 막았다)
    return finish_write(wiki, args, "adopt", recs, warnings, skip_clean=True)


