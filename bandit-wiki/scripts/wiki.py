VALIDATION_SUBCODES = {"MISSING_FIELD", "BAD_ID", "NEW_AREA", "TITLE_TOO_LONG", "REPLACED_BY_MISSING",
                       "REPLACED_BY_UNKNOWN", "BAD_DATE", "BAD_FIELD", "DUPLICATE_ID"}


def validate(wiki: Wiki, rec: dict, others: Dict[str, dict]) -> Tuple[List[dict], List[dict]]:
    """에러(저장 거절)와 경고(질문) 목록. others = 다른 결정들의 현재 상태."""
    errors, warnings = [], []
    did = rec.get("id") or ""
    missing = [FIELD_TO_LABEL[k] for k in REQUIRED_FIELDS if rec.get(k) in (None, "")]
    if not did:
        missing.insert(0, "ID")
    if missing:
        errors.append(finding("MISSING_FIELD", "빠진 칸: " + ", ".join(missing), fields=missing))
    if did and not ID_RE.match(did):
        errors.append(finding("BAD_ID", f"ID '{did}'는 영역.주제.규칙 형식(영문 소문자·숫자·하이픈)이 아니에요."))
    area = did.split(".")[0] if did else ""
    if did and ID_RE.match(did) and area not in wiki.cfg.get("areas", []):
        errors.append(finding("NEW_AREA", f"영역 '{area}'이 config.json에 없어요. 새 영역은 사람이 config.json에 추가해요."))
    title = rec.get("title") or ""
    if len(title) > TITLE_MAX:
        errors.append(finding("TITLE_TOO_LONG", f"제목이 {len(title)}자예요. 공백 포함 {TITLE_MAX}자 이하로 줄여 주세요."))
    if rec.get("review_by") and not DATE_RE.match(rec["review_by"]):
        errors.append(finding("BAD_DATE", f"다시 볼 날 '{rec['review_by']}'은 YYYY-MM-DD 형식이어야 해요."))
    if rec.get("status") == "deprecated":
        rb = rec.get("replaced_by") or []
        if not rb:
            errors.append(finding("REPLACED_BY_MISSING", "폐기에는 대체 결정 ID가 필요해요."))
        for x in rb:
            if x == did or x not in others:
                errors.append(finding("REPLACED_BY_UNKNOWN", f"대체 ID '{x}'인 결정이 없어요."))
    if rec.get("status") != "active":
        return errors, warnings

    value = rec.get("value") or ""
    if rec.get("always_on"):
        limit = int(wiki.cfg.get("always_on_limit", 10))
        count = 1 + sum(1 for o in others.values()
                        if o["id"] != did and o.get("always_on") and o.get("status") == "active")
        if count > limit:
            errors.append(finding("ALWAYS_ON_LIMIT", f"항상 적용 결정이 {count}개가 돼요 (최대 {limit}개)."))
    if DATE_IN_VALUE_RE.search(value) and not rec.get("review_by"):
        errors.append(finding("REVIEW_DATE_REQUIRED", "값에 날짜나 기한이 있어요. 다시 볼 날(--review-by YYYY-MM-DD)을 적어 주세요."))

    # --- 경고 ---
    comps = [w for w in wiki.cfg.get("comparatives", []) if w in value]
    if comps and re.search(r"\d", value) and not rec.get("interpretation"):
        warnings.append(finding("AMBIGUOUS_COMPARATIVE",
                                f"값에 '{comps[0]}'가 있어요. 이 숫자는 넘으면 안 되는 최대치인가요, 맞춰야 하는 값인가요?",
                                next="답을 --interpretation \"…\" 한 줄로 남기세요.", words=comps))
    vague = [w for w in wiki.cfg.get("vague_words", []) if w in value]
    if vague:
        warnings.append(finding("VAGUE_WORD", f"'{vague[0]}'는 사람마다 다르게 읽혀요. 확인할 수 있는 조건(숫자, 경우)으로 바꿀 수 있나요?", words=vague))
    multi = [w for w in wiki.cfg.get("one_rule_words", []) if w in value]
    if multi:
        warnings.append(finding("MULTI_RULE", f"값에 '{multi[0]}'가 있어요. 규칙이 둘이면 결정을 나누세요.", words=multi))
    for g in (rec.get("scope") or {}).get("code") or []:
        if count_glob(wiki, g) == 0:
            sug = suggest_paths(wiki, g)
            hint = f" 혹시 이 경로인가요: {', '.join(sug)}" if sug else ""
            warnings.append(finding("SCOPE_PATH_MISSING", f"적용 범위 '{g}'에 맞는 파일이 없어요.{hint}", glob=g, suggestions=sug))
    for oid in sorted(others):
        o = others[oid]
        if oid == did or o.get("status") != "active":
            continue
        score = max(jaccard(title, o.get("title") or ""), jaccard(value, o.get("value") or ""))
        if score >= DUPLICATE_THRESHOLD:
            warnings.append(finding("DUPLICATE_SUSPECT", f"'{oid}'와 비슷해요 (유사도 {score:.2f}). 같은 결정이면 새로 만들지 말고 그 결정을 바꾸세요.",
                                    other=oid, score=round(score, 2)))
    id_nums, val_nums = numbers_in_id(did), numbers_in_value(value)
    if id_nums and val_nums and not (id_nums & val_nums):
        warnings.append(finding("ID_VALUE_MISMATCH", f"ID에는 숫자 {sorted(id_nums)}가 있는데 값의 숫자는 {sorted(val_nums)}예요. ID와 값이 맞나요?"))
    title_nums = numbers_in_value(title)
    if title_nums and val_nums and not title_nums <= val_nums:
        warnings.append(finding("ID_VALUE_MISMATCH", f"제목에는 숫자 {sorted(title_nums)}가 있는데 값의 숫자는 {sorted(val_nums)}예요. 제목도 바꿔야 하나요?"))
    return errors, warnings


def raise_if_errors(errors: List[dict]) -> None:
    if not errors:
        return
    codes = [e["code"] for e in errors]
    if any(c in VALIDATION_SUBCODES for c in codes):
        code, nxt = "VALIDATION_FAILED", "빠지거나 틀린 칸을 채워 다시 실행하세요. 모르는 칸은 지어내지 말고 사람에게 물어보세요."
    elif "ALWAYS_ON_LIMIT" in codes:
        code, nxt = "ALWAYS_ON_LIMIT", "항상 적용 결정 하나를 --always-on no 로 내리거나, 이번 결정을 항상 적용 없이 저장하세요."
    else:
        code, nxt = codes[0], "값에 날짜·기한이 있으면 --review-by YYYY-MM-DD 로 다시 볼 날을 적으세요."
    raise WikiError(code, "저장할 수 없어요.", nxt, details=errors)


