_ZERO_WIDTH = dict.fromkeys(map(ord, "​‌‍⁠﻿"), None)


def normalize(text: Optional[str]) -> str:
    """되돌림·변화 없음 판정용: NFKC → 모든 공백 제거 → 끝 마침표 제거."""
    s = unicodedata.normalize("NFKC", text or "").translate(_ZERO_WIDTH)
    s = re.sub(r"\s+", "", s)
    return s.rstrip(".。")


def bigrams(text: str) -> set:
    n = normalize(text)
    if len(n) < 2:
        return {n} if n else set()
    return {n[i:i + 2] for i in range(len(n) - 1)}


def jaccard(a: str, b: str) -> float:
    x, y = bigrams(a), bigrams(b)
    if not x or not y:
        return 0.0
    return len(x & y) / len(x | y)


def clean_cell(text: Optional[str]) -> str:
    """CHANGELOG 칸: 줄바꿈·연속 공백 정리, | 를 / 로."""
    return re.sub(r"\s+", " ", (text or "").replace("|", "/")).strip()


def numbers_in_value(value: str) -> set:
    nums = {int(n) for n in re.findall(r"\d+", unicodedata.normalize("NFKC", value))}
    for word, _unit in KOREAN_COUNT_RE.findall(value):
        nums.add(KOREAN_COUNTS[word])
    return nums


def numbers_in_id(decision_id: str) -> set:
    nums = set()
    for token in re.split(r"[.-]", decision_id):
        if token in NUMBER_WORDS:
            nums.add(NUMBER_WORDS[token])
        m = re.match(r"^(\d+)[a-z]*$", token)
        if m:
            nums.add(int(m.group(1)))
    return nums


def split_list(text: Optional[str]) -> List[str]:
    """쉼표 목록. {a,b} 같은 중괄호 안 쉼표는 나누지 않는다."""
    if not text:
        return []
    out, buf, depth = [], "", 0
    for ch in text:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth = max(0, depth - 1)
        if ch in ",，" and depth == 0:
            out.append(buf.strip())
            buf = ""
        else:
            buf += ch
    out.append(buf.strip())
    return [x for x in out if x]


def split_ids(text: Optional[str]) -> List[str]:
    return [x for x in re.split(r"[,，\s]+", text or "") if x]


