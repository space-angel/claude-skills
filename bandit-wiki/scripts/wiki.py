def atomic_write(path: Path, text: str) -> None:
    """임시 파일에 다 쓴 뒤 rename. 중간에 끊겨도 반쯤 쓴 파일이 남지 않는다."""
    path.parent.mkdir(parents=True, exist_ok=True)
    # mkstemp는 0600으로 만든다. 기존 파일 권한을 지키고, 새 파일은 umask를 따른다 (CLAUDE.md가 0600이 되지 않게)
    try:
        mode = path.stat().st_mode & 0o777
    except FileNotFoundError:
        cur = os.umask(0)
        os.umask(cur)
        mode = 0o666 & ~cur
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix="." + path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, str(path))
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def append_line(path: Path, line: str) -> None:
    """append-only 파일에 한 줄 붙인다. 기존 내용은 절대 다시 쓰지 않는다."""
    path.parent.mkdir(parents=True, exist_ok=True)
    prefix = ""
    if path.exists() and path.stat().st_size > 0:
        with open(path, "rb") as f:
            f.seek(-1, os.SEEK_END)
            if f.read(1) != b"\n":
                prefix = "\n"
    with open(path, "a", encoding="utf-8", newline="\n") as f:
        f.write(prefix + line.rstrip("\n") + "\n")
        f.flush()
        os.fsync(f.fileno())


def append_jsonl(path: Path, obj: dict) -> None:
    append_line(path, json.dumps(obj, ensure_ascii=False))


def read_jsonl(path: Path) -> List[dict]:
    if not path.exists():
        return []
    out = []
    for no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            raise WikiError("CORRUPT_JSONL", f"{path.name} {no}번째 줄을 읽을 수 없어요.",
                            "git diff로 그 줄을 보고, 병합 충돌 표시(<<<<<<<)가 남았으면 두 줄 모두 남기고 표시만 지우세요.")
    return out


def read_text(path: Path) -> Optional[str]:
    return path.read_text(encoding="utf-8") if path.exists() else None


