def main(argv: Optional[List[str]] = None) -> int:
    parser = build_parser()
    argv = sys.argv[1:] if argv is None else argv
    try:
        args = parser.parse_args(argv)
    except SystemExit as e:
        if "--hook" in argv:  # hook은 사용법 오류여도 작업을 막지 않는다
            return 0
        return int(e.code or 0)
    if not getattr(args, "func", None):
        parser.print_help()
        return 2
    args.json = bool(getattr(args, "json", False))
    args.wiki_root = find_root(args)
    hook = bool(getattr(args, "hook", False))
    for name in ("apply", "by", "actor", "source", "kind"):
        if not hasattr(args, name):
            setattr(args, name, None if name != "apply" else False)
    try:
        return args.func(args)
    except WikiError as e:
        if hook:
            return 0
        if args.json:
            emit_json(e.as_dict())
        else:
            lines = [f"{e.code}: {e.message}"] + [f"  - {d['code']}: {d['message']}" for d in e.details] + [f"다음에 할 일: {e.next_action}"]
            sys.stderr.write("\n".join(lines) + "\n")
        return e.exit_code
    except Exception as e:  # hook은 절대 작업을 막지 않는다
        if hook:
            return 0
        raise


if __name__ == "__main__":
    sys.exit(main())
