CL_LINE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}) \| ")
CL_VER_RE = re.compile(r"^(\S+)\s+(new|\d+)\s*→\s*(\d+)$")
SKIP_IMPORT_FILES = {"INDEX.md", "CHANGELOG.md", "README.md"}


def parse_bandit_changelog(text: str) -> Tuple[List[dict], List[dict]]:
    entries, problems = [], []
    for no, line in enumerate(text.splitlines(), 1):
        if not CL_LINE_RE.match(line):
            continue
        cells = [c.strip() for c in line.split(" | ")]
        if len(cells) != 6:
            problems.append(finding("IMPORT_BAD_LINE", f"CHANGELOG {no}번째 줄의 칸이 {len(cells)}개예요 (6개여야 해요).", line=no))
            continue
        m = CL_VER_RE.match(cells[2])
        if not m:
            problems.append(finding("IMPORT_BAD_LINE", f"CHANGELOG {no}번째 줄의 'ID 이전→새' 칸을 읽지 못했어요.", line=no))
            continue
        entries.append({"line": no, "at": cells[0], "by": cells[1], "id": m.group(1), "from": m.group(2),
                        "to": int(m.group(3)), "values": cells[3], "reason": cells[4], "source": cells[5]})
    return entries, problems


def split_values(text: str, prev_value: Optional[str]) -> Tuple[str, str]:
    if prev_value and text.startswith(prev_value + " → "):
        return prev_value, text[len(prev_value) + 3:]
    if " → " in text:
        a, b = text.split(" → ", 1)
        return a, b
    return "", text


def import_states(fstate: dict, entries: List[dict], warn: List[dict]) -> List[dict]:
    """한 결정의 CHANGELOG 줄 → 버전별 상태 목록."""
    states: List[dict] = []
    for e in entries:
        prev = states[-1] if states else None
        old, new = split_values(e["values"], prev["value"] if prev else None)
        st = dict(prev) if prev else {"value": None, "scope": None, "status": "active", "replaced_by": []}
        st.update({"reason": e["reason"], "by": e["by"], "at": e["at"], "origin": e["source"], "kind": "rule",
                   "line": e["line"]})
        if e["from"] == "new":
            st.update({"value": new, "kind": "addition"})
        elif old.startswith("적용 범위:") and new.startswith(("코드:", "API:", "화면:", "문서:", "적용 범위:")):
            st["scope"] = parse_scope(new.replace("적용 범위:", "", 1))
            if prev is not None:
                for s in reversed(states):
                    if s["scope"] is not None:
                        break
                    s["scope"] = parse_scope(old.replace("적용 범위:", "", 1))
        else:
            m = re.match(r"^폐기\(대체:\s*(.*)\)$", new)
            if m:
                st.update({"status": "deprecated", "replaced_by": split_ids(m.group(1)), "kind": "deprecate"})
            else:
                st["value"] = new
        if prev is None and e["from"] != "new":
            warn.append(finding("IMPORT_NO_NEW_LINE", f"{fstate['id']}: CHANGELOG에 처음 등록 줄이 없어 v{int(e['from'])}를 이전 값으로 만들었어요."))
            base = {"value": old, "scope": None, "status": "active", "replaced_by": [], "reason": "(가져오기: 처음 기록 없음)",
                    "by": e["by"], "at": e["at"], "origin": e["source"], "kind": "addition", "version": int(e["from"]),
                    "line": e["line"] - 0.5}
            states.append(base)
            prev = base
        st["version"] = (prev["version"] + 1) if prev else e["to"]
        if st["version"] != e["to"]:
            warn.append(finding("IMPORT_VERSION_RENUMBERED", f"{fstate['id']}: CHANGELOG {e['line']}번째 줄 v{e['to']}를 v{st['version']}로 다시 매겼어요."))
        states.append(st)
    return states


def cmd_import_bandit(args) -> int:
    wiki = Wiki(args.wiki_root)
    src = Path(args.dir).expanduser()
    if not src.is_dir():
        raise WikiError("NOT_FOUND", f"폴더 '{src}'가 없어요.", "반딧 team-wiki 폴더 경로를 다시 확인하세요.", exit_code=2)
    if wiki.history():
        raise WikiError("IMPORT_NOT_EMPTY", "이미 기록(history.jsonl)이 있는 위키에는 가져올 수 없어요.", "새 저장소에서 init 한 직후에 import-bandit 을 실행하세요.")
    warn: List[dict] = []
    files: Dict[str, dict] = {}
    preambles: Dict[str, str] = {}
    for p in sorted(src.glob("*.md")):
        if p.name in SKIP_IMPORT_FILES:
            continue
        pre, blocks, _odd = parse_decision_text(p.read_text(encoding="utf-8"))
        valid = [b for b in blocks if ID_RE.match(b["id"])]
        for b in blocks:
            if not ID_RE.match(b["id"]):
                warn.append(finding("IMPORT_BAD_ID", f"{p.name}: '{b['id']}'는 ID 형식이 아니라 건너뛰어요."))
        for b in valid:
            st, problems = block_to_state(b)
            for pr in problems:
                warn.append(finding(pr["code"], f"{b['id']}: {pr['message']}"))
            if b["unknown"]:
                warn.append(finding("IMPORT_UNKNOWN_FIELD", f"{b['id']}: 모르는 칸 {', '.join(b['unknown'])} (버려요)"))
            files[b["id"]] = st
            area = b["id"].split(".")[0]
            if area not in preambles:
                preambles[area] = pre
            else:
                if pre and pre != preambles[area]:
                    warn.append(finding("IMPORT_SPLIT_AREA", f"영역 {area}이 여러 파일에 나뉘어 있어요 ({p.name}). 하나로 합쳐요."))
    cl_text = read_text(src / "CHANGELOG.md") or ""
    entries, problems = parse_bandit_changelog(cl_text)
    warn += problems
    by_id: Dict[str, List[dict]] = {}
    for e in entries:
        by_id.setdefault(e["id"], []).append(e)
    for did in sorted(set(by_id) - set(files)):
        warn.append(finding("IMPORT_ORPHAN_CHANGELOG", f"{did}: CHANGELOG에는 있는데 결정 파일에 없어 건너뛰어요."))
    records, order = [], []
    for did in sorted(files):
        fs = files[did]
        missing = [FIELD_TO_LABEL[k] for k in ("title", "value", "reason") if not fs.get(k)]
        if missing:
            warn.append(finding("IMPORT_MISSING_FIELD", f"{did}: 빠진 칸 {', '.join(missing)} — '(가져오기: 비어 있음)'으로 채워요."))
        states = import_states(fs, by_id.get(did, []), warn)
        if not states:
            warn.append(finding("IMPORT_NO_CHANGELOG", f"{did}: CHANGELOG 줄이 없어 파일 내용으로 v{fs.get('version') or 1} 하나만 만들어요."))
        fallback_at = entries[-1]["at"] if entries else iso(wiki.now())[:16].replace("T", " ")
        last = states[-1] if states else None
        if last is None or effective_value({"value": last["value"], "status": last["status"], "replaced_by": last["replaced_by"]}) != \
                effective_value(fs if fs.get("status") else dict(fs, status="active")):
            if last is not None:
                warn.append(finding("IMPORT_DRIFT", f"{did}: 파일의 현재 값이 CHANGELOG 마지막 값과 달라 파일 값으로 한 버전을 더 만들어요."))
            states.append({"value": fs.get("value"), "scope": fs.get("scope"), "status": fs.get("status") or "active",
                           "replaced_by": fs.get("replaced_by"), "reason": "(가져오기: 파일의 현재 값)",
                           "by": last["by"] if last else (wiki.identity(args.by, required=False) or "import"),
                           "at": last["at"] if last else fallback_at, "origin": "", "kind": "rule" if last else "addition",
                           "version": (last["version"] + 1) if last else (fs.get("version") or 1),
                           "line": 10 ** 9})
        elif fs.get("version") and fs["version"] != last["version"]:
            warn.append(finding("IMPORT_VERSION_MISMATCH", f"{did}: 파일 버전 v{fs['version']}과 CHANGELOG 버전 v{last['version']}이 달라요. 기록 버전을 따라요."))
        for i, st in enumerate(states):
            is_last = i == len(states) - 1
            reason = st["reason"] or "(가져오기: 비어 있음)"
            origin_reason = None
            if is_last and fs.get("reason") and fs["reason"] != reason:
                reason, origin_reason = fs["reason"], reason  # 파일의 이유는 결정에, CHANGELOG 이유는 따로
            rec = new_record({}, id=did, version=st["version"], title=fs.get("title") or "(가져오기: 비어 있음)",
                             value=st["value"] or fs.get("value") or "(가져오기: 비어 있음)", reason=reason, origin_reason=origin_reason,
                             scope=st["scope"] if st["scope"] is not None else fs.get("scope"),
                             always_on=bool(fs.get("always_on")), status=st["status"], replaced_by=st["replaced_by"],
                             locked=fs.get("locked") if is_last else False, review_by=fs.get("review_by") if is_last else None,
                             interpretation=fs.get("interpretation") if is_last else None, change_kind="import",
                             evidence=fs.get("evidence") if is_last else None, source="import", by=st["by"], actor="human",
                             at=iso(parse_iso(st["at"].replace(" ", "T") if "T" not in st["at"] else st["at"], wiki.tz)),
                             origin_source=LABEL_TO_SOURCE.get(st["origin"], ""), import_kind=st["kind"])
            prevs = [r for r in records if r["id"] == did]
            if prevs and rec["status"] == "active":
                for old in reversed(prevs[:-1]):
                    if normalize(old["value"]) == normalize(rec["value"]) and normalize(prevs[-1]["value"]) != normalize(rec["value"]):
                        rec["is_revert"], rec["reverted_to"], rec["import_kind"] = True, old["version"], "revert"
                        break
            records.append(rec)
            order.append((st["line"], did, st["version"]))
    # history 순서 = CHANGELOG 줄 순서 (줄이 없는 것은 맨 뒤, ID 순)
    records = [r for _k, r in sorted(zip(order, records), key=lambda kv: kv[0])]
    areas = sorted({r["id"].split(".")[0] for r in records})
    new_areas = [a for a in areas if a not in wiki.cfg.get("areas", [])]
    summary = {"decisions": len(files), "versions": len(records), "areas": areas, "new_areas": new_areas,
               "warnings": warn}
    if not args.apply:
        if args.json:
            emit_json(dict(summary, ok=True, applied=False))
            return 0
        say(f"[미리보기] {src} 에서 결정 {len(files)}개, 버전 {len(records)}개를 가져와요.")
        say(f"  영역: {', '.join(areas)}" + (f" (config.json에 새로 추가: {', '.join(new_areas)})" if new_areas else ""))
        for w in warn:
            say(f"  - {w['code']}: {w['message']}")
        say("가져오려면 같은 명령에 --apply를 붙이세요.")
        return 0
    if new_areas:
        cfg = json.loads((wiki.root / "config.json").read_text(encoding="utf-8"))
        cfg["areas"] = list(cfg.get("areas", [])) + new_areas
        atomic_write(wiki.root / "config.json", json.dumps(cfg, ensure_ascii=False, indent=2) + "\n")
        wiki.cfg["areas"] = cfg["areas"]
    for r in records:
        wiki.add_history(r)
    for a in areas:
        pre = preambles.get(a) or default_preamble(a)
        recs = [r for r in wiki.latest().values() if r["id"].split(".")[0] == a]
        atomic_write(wiki.area_path(a), render_area_file(pre, recs))
    wiki.log("import", f"{src.name}: 결정 {len(files)}개, 버전 {len(records)}개, 경고 {len(warn)}건")
    written = apply_sync(wiki)
    if args.json:
        emit_json(dict(summary, ok=True, applied=True, synced=written))
        return 0
    say(f"가져왔어요: 결정 {len(files)}개, 버전 {len(records)}개, 영역 {', '.join(areas)}")
    for w in warn:
        say(f"  - {w['code']}: {w['message']}")
    say("다시 만든 파일: " + ", ".join(w.split(" ", 1)[1] for w in written))
    return 0


